  function t(lang, key) {
    return (dict[lang] && dict[lang][key]) || dict.es[key] || key;
  }

  function applyLanguage(lang) {
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(lang, el.getAttribute('data-i18n'));
    });
    document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.title = t(lang, el.getAttribute('data-i18n-title'));
    });
    document.querySelectorAll('[data-i18n-html]').forEach(function (el) {
      el.innerHTML = t(lang, el.getAttribute('data-i18n-html'));
    });
    const titleKey = document.body.getAttribute('data-title-key');
    if (titleKey) document.title = t(lang, titleKey);
    localStorage.setItem(LANG_KEY, lang);
    document.querySelectorAll('[data-lang-option]').forEach(function (el) {
      const active = el.getAttribute('data-lang-option') === lang;
      el.classList.toggle('lang-active', active);
      el.setAttribute('aria-current', active ? 'true' : 'false');
    });
  }

  function init() {
    document.querySelectorAll('[data-lang-option]').forEach(function (el) {
      el.addEventListener('click', function (e) {
        e.preventDefault();
        applyLanguage(el.getAttribute('data-lang-option'));
      });
    });
    const year = document.getElementById('year');
    if (year) year.textContent = new Date().getFullYear();
    const saved = localStorage.getItem(LANG_KEY);
    const browser = (navigator.language || 'es').toLowerCase();
    const detected = saved || (browser.startsWith('pt') ? 'pt' : browser.startsWith('en') ? 'en' : 'es');
    applyLanguage(detected);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
